#!/bin/bash
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "=========================================================="
echo " Deploying TaskFlow Native Android App to Connected Phone "
echo "=========================================================="

# 1. Locate adb
ADB_BIN="adb"
if ! command -v adb &> /dev/null; then
    if [ -f "$HOME/Library/Android/sdk/platform-tools/adb" ]; then
        ADB_BIN="$HOME/Library/Android/sdk/platform-tools/adb"
    else
        echo "❌ Error: 'adb' tool was not found in PATH or ~/Library/Android/sdk/platform-tools/"
        exit 1
    fi
fi
echo "Using adb: $ADB_BIN"

# 2. Check connected devices
echo "Checking for connected Android devices..."
DEVICES=$("$ADB_BIN" devices | grep -v "List of devices" | grep "device$" || true)

if [ -z "$DEVICES" ]; then
    echo "❌ No Android device detected!"
    echo ""
    echo "To connect your Android phone:"
    echo "  1. Connect your phone to your Mac with a USB-C / USB cable."
    echo "  2. On your phone, go to Settings -> About Phone -> tap 'Build Number' 7 times to enable Developer Mode."
    echo "  3. Go to Settings -> System / Developer Options -> enable 'USB Debugging'."
    echo "  4. When prompted on your phone screen, tap 'Allow USB Debugging'."
    echo "  5. Re-run this script: ./deploy-to-phone.sh"
    echo ""
    "$ADB_BIN" devices
    exit 1
fi

echo "✅ Device connected:"
echo "$DEVICES"
echo ""

# 3. Locate the APK
APK_FILE=$(find target/gluonfx/aarch64-android/gvm/ dist/ -maxdepth 2 -name "*.apk" 2>/dev/null | head -n 1)

if [ -z "$APK_FILE" ] || [ ! -f "$APK_FILE" ]; then
    echo "❌ Error: Could not find compiled APK."
    echo "Please build the APK first by running:"
    echo "  ./build-android.sh"
    echo "Or download the APK generated by your GitHub Actions workflow."
    exit 1
fi

echo "📱 Found APK: $APK_FILE"
echo "Installing APK to connected Android device..."
"$ADB_BIN" install -r "$APK_FILE"

echo ""
echo "🚀 Launching TaskFlow on the device..."
"$ADB_BIN" shell monkey -p com.todo -c android.intent.category.LAUNCHER 1

echo ""
echo "=========================================================="
echo "🎉 TaskFlow successfully deployed and running on your phone!"
echo "=========================================================="
echo "To view live logs from the app, run:"
echo "  $ADB_BIN logcat -s GraalVM:* TaskFlow:* ActivityManager:*"
